import type { ItemDef } from './catalog';
import type { MoveKind } from '../map/types';

/**
 * Animal Island edible catalog (the third map). Data only: size, tier, level and points are derived from
 * the dimensions in catalog.ts like every other item. Priority P0 = first playable set, P1 = full v1,
 * P2 = polish (see ANIMAL-ISLAND.md). `biomes` = where the generator may place it, `motion` = how it moves
 * ('herd' walks like 'wander' but is placed in groups; '-' = static). Builders: build-animals.ts (rigs),
 * build-nature.ts (flora, rocks, hills), build-zoo.ts (zoo, farm, laboratory). Nine greenery items
 * (flower, grass_tuft, bush_small, bush_large, tree_small, palm_tree, hedge, tree, tree_big) are shared with City Island.
 */
export type Biome =
  | 'meadow'
  | 'forest'
  | 'savanna'
  | 'wetland'
  | 'highlands'
  | 'beach'
  | 'jungle'
  | 'zoo'
  | 'lab'
  | 'farm'
  | 'river'
  | 'bank'
  | 'everywhere';
export type Motion = MoveKind | 'herd' | '-';
export type AnimalPriority = 'P0' | 'P1' | 'P2';
export type AnimalDef = ItemDef & {
  priority: AnimalPriority;
  biomes: Biome[];
  motion: Motion;
};

