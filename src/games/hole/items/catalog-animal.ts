/** Window material of the lab buildings (the walls tile windows); everything else is plain vertex colour. */
const STYLE: Record<string, ItemDef['style']> = {
  greenhouse: 'glass',
  biodome: 'glass',
  lab_block: 'punched',
  lab_wing: 'ribbon',
  lab_hq: 'glass',
  lab_tower: 'ribbon',
};

type Opts = Partial<Pick<ItemDef, 'variants' | 'paints'>>;

function def(
  id: string,
  name: string,
  group: ItemDef['group'],
  w: number,
  d: number,
  h: number,
  where: string,
  priority: AnimalPriority,
  biomes: Biome[],
  motion: Motion,
  o: Opts = {},
): AnimalDef {
  return {
    id,
    name,
    group,
    w,
    d,
    h,
    where,
    variants: o.variants ?? 1,
    style: STYLE[id] ?? 'prop',
    paints: o.paints,
    map: 'animal',
    priority,
    biomes,
    motion,
  };
}

