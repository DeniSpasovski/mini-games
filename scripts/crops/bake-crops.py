"""
Bake the field crop models (CC BY 4.0, credits: THIRD-PARTY.md) into src/games/rally/assets/builders/crop-models.data.ts:
the models' own triangles, normals, uvs and texture (re-encoded as a 512 px JPEG), scaled to metres, standing on the
origin (y up). The sources are not in the repository (sources/maps/ajvatovci/, see the map's DETAILS.md).

  python scripts/crops/bake-crops.py sources/maps/ajvatovci

Packed mesh layout (little endian): u16 vertices, u16 0, f32 lo[3], f32 size[3], u16 x3 position (quantised in the box),
i8 x3 normal, u16 x2 uv (0..1), u32 index count, u16 indices.
"""
import base64
import io
import os
import struct
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'car-model'))
from gltfio import accessor, load_glb, node_matrix  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'games', 'rally', 'assets', 'builders',
                   'crop-models.data.ts')

# id, file, height (m) the tallest point is scaled to.
MODELS = [
    ('wheat', 'realistic-wheat.glb', 0.95),
    ('corn', 'corn-corn-corn.glb', 2.3),
]


def mesh_of(g, binary):
    """Every triangle primitive in world space: positions, normals, uvs, indices (one merged mesh)."""
    P, N, U, I = [], [], [], []

    def walk(i, M):
        n = g['nodes'][i]
        M = M @ node_matrix(n)
        if 'mesh' in n:
            for p in g['meshes'][n['mesh']]['primitives']:
                a = p['attributes']
                pos = accessor(g, binary, a['POSITION'])
                nrm = accessor(g, binary, a['NORMAL'])
                uv = accessor(g, binary, a['TEXCOORD_0'])
                idx = accessor(g, binary, p['indices']).astype(np.int64).ravel()
                R = M[:3, :3]
                nm = np.linalg.inv(R).T
                base = sum(len(x) for x in P)
                P.append((R @ pos.T).T + M[:3, 3])
                nn = (nm @ nrm.T).T
                N.append(nn / np.maximum(np.linalg.norm(nn, axis=1, keepdims=True), 1e-9))
                U.append(uv)
                I.append(idx + base)
        for c in n.get('children', []):
            walk(c, M)

    for s in g['scenes'][g.get('scene', 0)]['nodes']:
        walk(s, np.eye(4))
    return np.concatenate(P), np.concatenate(N), np.concatenate(U), np.concatenate(I)


def weld(P, N, U, I):
    key = np.round(np.hstack([P * 1e4, N * 100, U * 1e4])).astype(np.int64)
    _, first, inv = np.unique(key, axis=0, return_index=True, return_inverse=True)
    return P[first], N[first], U[first], inv.ravel()[I]


def pack(P, N, U, I):
    lo = P.min(0)
    size = np.maximum(P.max(0) - lo, 1e-6)
    q = np.round((P - lo) / size * 65535).astype('<u2')
    n8 = np.clip(np.round(N * 127), -127, 127).astype('<i1')
    uv = np.round(np.clip(U, 0, 1) * 65535).astype('<u2')
    out = struct.pack('<HH', len(P), 0) + struct.pack('<3f', *lo) + struct.pack('<3f', *size)
    out += q.tobytes() + n8.tobytes() + uv.tobytes()
    out += struct.pack('<I', len(I)) + I.astype('<u2').tobytes()
    return base64.b64encode(out).decode()


def texture(g, binary):
    im = g['images'][0]
    bv = g['bufferViews'][im['bufferView']]
    off = bv.get('byteOffset', 0)
    img = Image.open(io.BytesIO(binary[off:off + bv['byteLength']])).convert('RGB').resize((512, 512), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, 'JPEG', quality=88)
    return 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()


def main(src):
    rows = []
    for mid, name, height in MODELS:
        g, binary = load_glb(os.path.join(src, name))
        P, N, U, I = mesh_of(g, binary)
        lo, hi = P.min(0), P.max(0)
        c = (lo + hi) / 2
        s = height / (hi[1] - lo[1])
        P = (P - [c[0], lo[1], c[2]]) * s
        # glTF uvs have v down; three flips textures (flipY), so v = 1 - v here.
        U = U.copy()
        U[:, 1] = 1 - U[:, 1]
        P, N, U, I = weld(P, N, U, I)
        radius = float(np.max(np.hypot(P[:, 0], P[:, 2])))
        print(f'{mid}: {len(P)} vertices, {len(I) // 3} triangles, {height} m tall, radius {radius:.2f} m')
        rows.append(
            f"  {mid}: {{\n    height: {height},\n    radius: {radius:.2f},\n    mesh: '{pack(P, N, U, I)}',\n"
            f"    texture:\n      '{texture(g, binary)}',\n  }},\n")
    with open(OUT, 'w') as f:
        f.write('// Generated by scripts/crops/bake-crops.py from the CC BY models credited in THIRD-PARTY.md. Do not edit.\n')
        f.write('export interface CropModelData {\n  /** Height (m) and widest reach from the stem (m). */\n'
                '  height: number;\n  radius: number;\n  /** Packed mesh (layout: see the baker). */\n  mesh: string;\n'
                '  /** The model\'s own texture (JPEG data URI). */\n  texture: string;\n}\n\n')
        f.write('export const CROP_MODELS: Record<\'wheat\' | \'corn\', CropModelData> = {\n')
        f.write(''.join(rows))
        f.write('};\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main(sys.argv[1])
