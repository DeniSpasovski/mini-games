"""
Bake a few trees and shrubs of three CC BY 4.0 Sketchfab packs by LOLIPOP (credits: THIRD-PARTY.md) into
src/games/rally/assets/builders/tree-packs.data.ts (the models' own triangles, normals and uvs, three levels of detail each)
and src/games/rally/assets/builders/tree-packs/<pack>-{bark,bark-n,leaf,leaf-n}.webp (their own textures, shrunk).
The packs are not in the repository (git-ignored sources/).

  python scripts/trees/bake-tree-packs.py <pine.glb> <lilac.glb> <bush.glb>

Every variant stands on the origin (trunk foot, y up, metres). Packed mesh (little endian), per part and level:
u32 vertices, f32 lo[3], f32 size[3], f32 uvLo[2], f32 uvSize[2], then per vertex u16 x3 position (quantised in the box), i8 x3
normal, i8 pad, u16 x2 uv (quantised in the uv box; glTF: origin top left, the bark tiles), then u32 index count, u16 indices.
"""
import base64
import io
import os
import re
import struct
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'car-model'))
from gltfio import accessor, load_glb, node_matrix  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'games', 'rally', 'assets', 'builders')
OUT = os.path.join(ROOT, 'tree-packs.data.ts')
TEX = os.path.join(ROOT, 'tree-packs')

# pack id -> (glb argument, bark material, leaf material, variants (node name stem, LOD names)).
PACKS = {
    'pine': ('Bark_Mat', 'Clusters_Mat', ['Pine_medium_1', 'Pine_big_2', 'Pine_large_2']),
    'lilac': ('Bark_mat', 'Brunches_mat', ['Lilac_bush_3', 'Lilac_small_bush_3', 'Lilac_single_tree_2']),
    'bush': ('Bark_material', 'Brunch_material', ['Bush_big_002', 'Bush_medium_005', 'Bush_big_005']),
}
# Texture sizes (px across): bark colour / normal, leaf colour / normal.
# Model metres the root foot sinks into the ground (the pines' root flares rise ~0.5 m from their tips).
SINK = {'pine': 0.3}
SIZES = {'pine': (512, 512, 1024, 512), 'lilac': (512, 512, 1024, 512), 'bush': (512, 256, 512, 256)}


def meshes(g, binary):
    """node name -> list of (material name, positions, normals, uvs, indices) in world space."""
    out = {}

    def walk(i, M):
        n = g['nodes'][i]
        M = M @ node_matrix(n)
        if 'mesh' in n:
            for p in g['meshes'][n['mesh']]['primitives']:
                a = p['attributes']
                pos = accessor(g, binary, a['POSITION'])
                nrm = accessor(g, binary, a['NORMAL'])
                uv = accessor(g, binary, a['TEXCOORD_0'])
                idx = accessor(g, binary, p['indices']).astype(np.int64).ravel()
                R = M[:3, :3]
                nm = np.linalg.inv(R).T
                nn = (nm @ nrm.T).T
                nn /= np.maximum(np.linalg.norm(nn, axis=1, keepdims=True), 1e-9)
                mat = g['materials'][p['material']]['name']
                out.setdefault(n['name'], []).append((mat, (R @ pos.T).T + M[:3, 3], nn, uv, idx))
        for c in n.get('children', []):
            walk(c, M)

    for s in g['scenes'][g.get('scene', 0)]['nodes']:
        walk(s, np.eye(4))
    return out


def pack(P, N, U, I, origin):
    P = P - origin
    lo = P.min(axis=0)
    size = np.maximum(P.max(axis=0) - lo, 1e-6)
    q = np.round((P - lo) / size * 65535).astype('<u2')
    n8 = np.round(N * 127).astype('i1')
    ulo = U.min(axis=0)
    usize = np.maximum(U.max(axis=0) - ulo, 1e-6)
    u = np.round((U - ulo) / usize * 65535).astype('<u2')
    head = struct.pack('<I3f3f2f2f', len(P), *lo, *size, *ulo, *usize)
    v = np.zeros(len(P), dtype=[('p', '<u2', 3), ('n', 'i1', 3), ('pad', 'i1'), ('uv', '<u2', 2)])
    v['p'], v['n'], v['uv'] = q, n8, u
    return head + v.tobytes() + struct.pack('<I', len(I)) + I.astype('<u2').tobytes()


def texture(g, binary, mat, slot):
    m = next(x for x in g['materials'] if x['name'] == mat)
    if slot == 'color':
        t = m['pbrMetallicRoughness']['baseColorTexture']['index']
    else:
        t = m['normalTexture']['index']
    im = g['images'][g['textures'][t]['source']]
    bv = g['bufferViews'][im['bufferView']]
    off = bv.get('byteOffset', 0)
    return Image.open(io.BytesIO(binary[off:off + bv['byteLength']]))


def spent_blossom(im):
    """Lilac blooms in late April; the rest of the year the panicles are seed heads. Purple pixels -> olive brown, keeping
    their light and shade."""
    a = np.asarray(im).astype(np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    purple = (b > g + 2) & (r > g + 2)
    lum = 0.3 * r + 0.59 * g + 0.11 * b
    seed = np.array([112, 96, 60], np.float32) / 150.0
    for c in range(3):
        a[..., c] = np.where(purple, np.clip(lum * seed[c], 0, 255), a[..., c])
    return Image.fromarray(a.astype(np.uint8), 'RGBA')


def main():
    files = dict(zip(PACKS, sys.argv[1:4]))
    if len(files) != 3:
        sys.exit(__doc__)
    os.makedirs(TEX, exist_ok=True)
    lines = [
        '// Generated by scripts/trees/bake-tree-packs.py from three CC BY 4.0 packs by LOLIPOP (THIRD-PARTY.md). Do not edit.',
        'export interface PackLevel {',
        '  /** Packed meshes (layout: see the baker): the bark and the leaf cards. */',
        '  bark: string;',
        '  leaf: string;',
        '}',
        'export interface PackModel {',
        '  /** Height (m) and widest reach from the trunk (m). */',
        '  height: number;',
        '  radius: number;',
        '  /** Level of detail 0 (near) .. 2. */',
        '  lods: PackLevel[];',
        '}',
        '',
        "export const TREE_PACKS: Record<'pine' | 'lilac' | 'bush', PackModel[]> = {",
    ]
    for pid, (bark_m, leaf_m, stems) in PACKS.items():
        g, binary = load_glb(files[pid])
        ms = meshes(g, binary)
        sizes = SIZES[pid]
        for name, mat, slot, px in [
            ('bark', bark_m, 'color', sizes[0]),
            ('bark-n', bark_m, 'normal', sizes[1]),
            ('leaf', leaf_m, 'color', sizes[2]),
            ('leaf-n', leaf_m, 'normal', sizes[3]),
        ]:
            im = texture(g, binary, mat, slot)
            im = im.convert('RGBA' if name == 'leaf' else 'RGB').resize((px, px), Image.LANCZOS)
            if pid == 'lilac' and name == 'leaf':
                im = spent_blossom(im)
            path = os.path.join(TEX, f'{pid}-{name}.webp')
            im.save(path, 'WEBP', quality=82 if name != 'leaf-n' else 80, method=6, alpha_quality=90)
            print(path, os.path.getsize(path) // 1024, 'KB')
        lines.append(f'  {pid}: [')
        for stem in stems:
            levels = []
            origin = None
            height = radius = 0.0
            for lod in range(3):
                parts = {}
                for node, prims in ms.items():
                    if re.fullmatch(rf'{stem}_LOD{lod}_.*', node):
                        for mat, P, N, U, I in prims:
                            parts['bark' if mat == bark_m else 'leaf'] = (P, N, U, I)
                bark = parts['bark']
                if origin is None:
                    P = bark[0]
                    y0 = P[:, 1].min()
                    low = P[P[:, 1] < y0 + 0.3]
                    c = low[:, [0, 2]].mean(axis=0)
                    if pid == 'pine':
                        # A tree's root flares spread to one side: its axis is the trunk's middle 1.5-3 m up.
                        band = P[(P[:, 1] > y0 + 1.5) & (P[:, 1] < y0 + 3)][:, [0, 2]]
                        band = band[np.hypot(*(band - np.median(band, axis=0)).T) < 1]
                        c = (band.min(axis=0) + band.max(axis=0)) / 2
                    origin = np.array([c[0], y0 + SINK.get(pid, 0), c[1]])
                    allp = np.concatenate([parts['bark'][0], parts['leaf'][0]]) - origin
                    height = float(allp[:, 1].max())
                    radius = float(np.hypot(allp[:, 0], allp[:, 2]).max())
                levels.append((pack(*parts['bark'], origin), pack(*parts['leaf'], origin)))
                print(pid, stem, 'LOD', lod, len(parts['bark'][3]) // 3 + len(parts['leaf'][3]) // 3, 'tris')
            lines.append(f'    {{ height: {height:.2f}, radius: {radius:.2f}, lods: [')
            for b, lf in levels:
                lines.append("      { bark: '%s', leaf: '%s' }," % (base64.b64encode(b).decode(), base64.b64encode(lf).decode()))
            lines.append('    ] },')
        lines.append('  ],')
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(OUT, os.path.getsize(OUT) // 1024, 'KB')


main()
