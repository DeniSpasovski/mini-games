/**
 * Bakes the rally outcrop rocks (catalog `rock_outcrop`: rock bands breaking out of steep hillsides, world/outcrops.ts)
 * from two CC0 Poly Haven scans of weathered, layered rock faces with lichen and moss, Dario Barresi: "Rock Face 01" and
 * "Rock Face 02" (1k glTF downloads in sources/rally/polyhaven/rock_face_01, rock_face_02):
 *
 *   node scripts/rocks/bake-outcrops.mjs sources/rally/polyhaven
 *
 * -> src/games/rally/assets/builders/outcrop-models.data.ts and src/games/rally/engine/props/outcrop.{color,normal}.webp
 * (the two scans' colour maps side by side, 2048 x 1024; normal maps at half size).
 *
 * Both scans are open shells of a cliff section seen from the front (+Z), the back open: each is centred across (x),
 * stood on y = 0 and its front put at z = FRONT, in metres; the scatter sets the face looking downhill and buries its
 * back in the slope. Levels of detail: `LODS` triangles (scripts/rocks/mesh-kit.mjs packs, positions / UNIT).
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { lodChain, readPrimitive } from './mesh-kit.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const src = path.resolve(process.argv[2] ?? 'sources/rally/polyhaven');
const MODELS = ['rock_face_01', 'rock_face_02'];
/** Triangle budget per level of detail (near, mid, far). */
const LODS = [2400, 600, 160];
/** Packed position unit: 1 / 8192 m (|x| < 4 m). */
const UNIT = 8192;
/** Where the face's front ends up (m along +Z from the origin). */
const FRONT = 0.4;

const out = [];
MODELS.forEach((id, k) => {
  const { pos, nor, uv, idx } = readPrimitive(
    path.join(src, id, `${id}_1k.gltf`),
  );
  let [x0, y0, z1, x1] = [Infinity, Infinity, -Infinity, -Infinity];
  let [z0, y1] = [Infinity, -Infinity];
  for (let i = 0; i < pos.length; i += 3) {
    x0 = Math.min(x0, pos[i]);
    x1 = Math.max(x1, pos[i]);
    y0 = Math.min(y0, pos[i + 1]);
    y1 = Math.max(y1, pos[i + 1]);
    z0 = Math.min(z0, pos[i + 2]);
    z1 = Math.max(z1, pos[i + 2]);
  }
  const cx = (x0 + x1) / 2;
  for (let i = 0; i < pos.length; i += 3) {
    pos[i] -= cx;
    pos[i + 1] -= y0;
    pos[i + 2] += FRONT - z1;
  }
  // Into this model's half of the atlas.
  for (let i = 0; i < uv.length; i += 2)
    uv[i] = (k + Math.min(1, Math.max(0, uv[i]))) / MODELS.length;
  const lods = lodChain(pos, nor, uv, idx, LODS, UNIT);
  const size = [x1 - x0, y1 - y0, z1 - z0];
  out.push({ id, size, lods });
  console.log(
    id,
    size.map((v) => v.toFixed(2)).join(' x '),
    'm,',
    lods.map((l) => l.tris).join(' / '),
    'tris',
  );
});

const ts = `// Generated by scripts/rocks/bake-outcrops.mjs from Poly Haven "Rock Face 01" / "Rock Face 02" (CC0). Do not edit.
export interface OutcropModelData {
  /** Size (m): width (x), height (y), depth (z, the face at +z). */
  size: [number, number, number];
  /** Packed mesh per level of detail (layout: scripts/rocks/mesh-kit.mjs, positions / ${UNIT}). */
  lods: string[];
}

export const OUTCROP_UNIT = ${UNIT};

export const OUTCROP_MODELS: OutcropModelData[] = [
${out.map((r) => `  // ${r.id}\n  { size: [${r.size.map((v) => v.toFixed(3)).join(', ')}], lods: [${r.lods.map((l) => `'${l.b64}'`).join(', ')}] },`).join('\n')}
];
`;
const dataFile = 'src/games/rally/assets/builders/outcrop-models.data.ts';
fs.writeFileSync(path.join(root, dataFile), ts);
// The repo's formatting, so a bake with nothing changed leaves no diff.
execFileSync('npx', ['prettier', '--write', dataFile], {
  cwd: root,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});

// Textures: the scans' colour maps side by side, normal maps at half size (Pillow).
const props = path.join(root, 'src/games/rally/engine/props');
for (const [part, name, size] of [
  ['diff', 'color', 1024],
  ['nor_gl', 'normal', 512],
]) {
  execFileSync(process.env.PYTHON ?? 'python', [
    '-I',
    '-c',
    `import sys
from PIL import Image
size = int(sys.argv[1]); files = sys.argv[3:]
out = Image.new('RGB', (size * len(files), size))
for i, f in enumerate(files):
    out.paste(Image.open(f).convert('RGB').resize((size, size), Image.LANCZOS), (i * size, 0))
out.save(sys.argv[2], quality=86, method=6)`,
    String(size),
    path.join(props, `outcrop.${name}.webp`),
    ...MODELS.map((id) =>
      path.join(src, id, 'textures', `${id}_${part}_1k.jpg`),
    ),
  ]);
}
console.log('wrote', out.length, 'outcrop models');
